#!/usr/bin/env python3
"""Generates packages/aethryon_store/lib/src/schemas.dart from schema/*.sql (single source of truth).
`python3 tools/gen_schema_dart.py --check` fails if the generated file is stale."""
import sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
def build():
    out = ["// GENERATED by tools/gen_schema_dart.py from schema/*.sql - do not edit by hand.\n"]
    for name, f in (("driveSchemaV1", "drive_schema.sql"), ("mailSchemaV1", "mail_schema.sql")):
        sql = (root / "schema" / f).read_text(encoding="utf-8")
        assert "'''" not in sql
        out.append(f"const {name} = r'''{sql}''';\n")
    return "\n".join(out)
target = root / "packages/aethryon_store/lib/src/schemas.dart"
text = build()
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        sys.exit("schemas.dart is stale: run python3 tools/gen_schema_dart.py")
    print("schemas.dart up to date")
else:
    target.write_text(text, encoding="utf-8"); print("written", target)
